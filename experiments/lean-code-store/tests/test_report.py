"""Tests of `lean_code_store.report`: the grouping of reported names and the printed tables."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import pytest

from lean_code_store.report import main, name_shape, stored_counts

pytestmark = [pytest.mark.unit, pytest.mark.timeout(5)]


def test_name_shape_groups_numbered_and_private_root_names() -> None:
    """`name_shape`: numbers become `N`; a private name with no prefix after the module is marked."""
    assert name_shape("_private.A.B.0.match_12") == "match_N (private, no prefix)"
    assert name_shape("_private.A.B.0.f.match_1.eq_2") == "eq_N"


LONG = " " * 491
"""Padding that makes each stored text longer than 400 characters."""


def _version(root: Path, key: str, decision: str) -> None:
    """A file version of module `M`: theorems `a` and `b` with long texts, a reported match
    function and its generated equation lemma; `a` has the given decision."""
    version = root / "versions" / key
    version.mkdir(parents=True)
    version.joinpath("entity_texts.jsonl").write_text("".join(
        json.dumps({"text_sha256": "h" + n, "text": f"theorem {n}{LONG}"}) + "\n" for n in "ab"))
    version.joinpath("entities.jsonl").write_text("".join(
        json.dumps({"file_key": key, "name": n, "kind": "theorem", "text_sha256": "h" + n}) + "\n" for n in "ab"))
    version.joinpath("counts.json").write_text(json.dumps({"counts": {"rule 4 declaration": 2}, "reported": [
        ["_private.M.0.match_1", "no rule"],
        ["_private.M.0.match_1.eq_1", "generated, no declaration at the end of its parents"]],
        "decisions": {"a": decision, "b": "declaration by 4", "_private.M.0.match_1": "reported by no rule",
                      "_private.M.0.match_1.eq_1": "generated by 5"}}))


def _snapshot(root: Path, snapshot: str, key: str, complete: bool = True) -> None:
    """A snapshot of module `M` with one file version; `complete` writes its `snapshots` row."""
    directory = root / "snapshots" / snapshot
    directory.mkdir(parents=True)
    directory.joinpath("snapshot_files.jsonl").write_text(json.dumps(
        {"snapshot_id": snapshot, "source_path": "M.lean", "module_name": "M", "file_key": key}) + "\n")
    if complete:
        directory.joinpath("snapshots.jsonl").write_text(json.dumps({"snapshot_id": snapshot}) + "\n")


def _report(root: Path, snapshot: str, capsys: pytest.CaptureFixture[str]) -> dict[str, dict[str, object]]:
    """The JSON that `report.main` prints for one snapshot."""
    rows = [{"target_module": "M", "target_name": n, "target_kind": "theorem", "only_user": ["M", "u"],
             "used_in_a_type": 0} for n in "ab"]
    root.joinpath("candidates.jsonl").write_text("".join(json.dumps(row) + "\n" for row in rows))
    with pytest.MonkeyPatch.context() as patch:
        patch.setattr("sys.argv", ["report", "--store", str(root), "--snapshot", snapshot,
                                   "--candidates", str(root / "candidates.jsonl"), "--sample", "1"])
        assert main() == 0
    printed: dict[str, dict[str, object]] = json.loads(capsys.readouterr().out)
    return printed


def test_report_main_prints_the_tables_of_one_snapshot(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    """`report.main` prints decisions, reported causes, counts and candidates of the requested
    snapshot only; `reported_table` includes a generated constant whose parent is reported, and
    `candidates_table` keeps the full text of a sampled declaration."""
    _version(tmp_path, "k1", "declaration by 4")
    _version(tmp_path, "k2", "generated by 2")
    _snapshot(tmp_path, "s1", "k1")
    _snapshot(tmp_path, "s2", "k2")
    printed = _report(tmp_path, "s1", capsys)
    assert printed["decisions"]["declaration by 4"] == [2, ["a", "b"]]
    assert "generated by 2" not in printed["decisions"]
    assert printed["reported"] == {"no rule: match_N (private, no prefix)": [1, ["_private.M.0.match_1"]],
                                   "generated, no declaration at the end of its parents: eq_N":
                                       [1, ["_private.M.0.match_1.eq_1"]]}
    assert printed["counts"] == {"rule 4 declaration": 2}
    candidates = printed["candidates"]
    assert candidates["count"] == 2 and candidates["by_kind"] == {"theorem, used_in_a_type=0": 2}
    first = min("ab", key=lambda name: hashlib.sha256(name.encode()).hexdigest())
    sample = candidates["sample"]
    assert isinstance(sample, list)
    assert [(row["target_name"], row["text"]) for row in sample] == [(first, f"theorem {first}{LONG}")]
    assert _report(tmp_path, "s2", capsys)["decisions"]["generated by 2"] == [1, ["a"]]


def test_report_refuses_an_incomplete_snapshot(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    """`snapshot_keys` refuses a snapshot without its `snapshots` row."""
    _version(tmp_path, "k", "declaration by 4")
    _snapshot(tmp_path, "s", "k", complete=False)
    with pytest.raises(ValueError, match="snapshot s has no snapshots row"):
        _report(tmp_path, "s", capsys)


def test_stored_counts_refuses_a_version_without_decisions(tmp_path: Path) -> None:
    """`stored_counts` names the file version of an older prototype and what to do."""
    version = tmp_path / "versions" / "k"
    version.mkdir(parents=True)
    version.joinpath("counts.json").write_text(json.dumps({"counts": {}, "reported": []}))
    with pytest.raises(ValueError, match="file version k has no decisions; extract the snapshot again"):
        stored_counts(tmp_path, "k")
